CREATE TABLE hotels (
    id_hotel INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_name VARCHAR(180) NOT NULL,
    brand_name VARCHAR(120) NOT NULL DEFAULT 'Spotki Hotels',
    star_rating INT NOT NULL DEFAULT 5,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(120) NOT NULL,
    phone VARCHAR(40),
    email VARCHAR(160),
    hero_image VARCHAR(500),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_users (
    id_admin INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(160),
    role VARCHAR(30) NOT NULL DEFAULT 'admin',
    id_hotel INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rooms (
    id_room INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hotel INT,
    room_number VARCHAR(30) NOT NULL UNIQUE,
    room_type VARCHAR(80) NOT NULL,
    floor_no INT NOT NULL DEFAULT 1,
    capacity INT NOT NULL DEFAULT 2,
    room_size VARCHAR(40),
    bed_type VARCHAR(120),
    price_per_night DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    hourly_rate DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    extra_guest_rate_percent DECIMAL(5,2) NOT NULL DEFAULT 25.00,
    image_url VARCHAR(500),
    gallery_urls TEXT,
    amenities TEXT,
    package_name VARCHAR(160),
    package_services TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'available',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    housekeeping_status VARCHAR(30),
    housekeeping_started_at TIMESTAMP,
    cleaned_at TIMESTAMP,
    note TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rooms_hotel FOREIGN KEY (id_hotel) REFERENCES hotels(id_hotel)
);

CREATE TABLE guests (
    id_guest INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(255),
    password_hash VARCHAR(255),
    customer_is_active BOOLEAN NOT NULL DEFAULT TRUE,
    identity_no VARCHAR(60),
    address TEXT,
    is_vip BOOLEAN NOT NULL DEFAULT FALSE,
    loyalty_points INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bookings (
    id_booking INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(30) NOT NULL UNIQUE,
    id_guest INT NOT NULL,
    id_room INT NOT NULL,
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    check_in_at TIMESTAMP,
    expected_check_out_at TIMESTAMP,
    checked_out_at TIMESTAMP,
    pricing_mode VARCHAR(20) NOT NULL DEFAULT 'night',
    contact_name VARCHAR(160),
    contact_phone VARCHAR(40),
    customer_edit_count INT NOT NULL DEFAULT 0,
    customer_edited_at TIMESTAMP,
    loyalty_awarded_at TIMESTAMP,
    adults INT NOT NULL DEFAULT 1,
    children INT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'booked',
    note TEXT,
    package_snapshot TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bookings_guest FOREIGN KEY (id_guest) REFERENCES guests(id_guest),
    CONSTRAINT fk_bookings_room FOREIGN KEY (id_room) REFERENCES rooms(id_room)
);

CREATE TABLE services (
    id_service INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(255) NOT NULL,
    unit VARCHAR(50) NOT NULL DEFAULT 'lan',
    price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE booking_services (
    id_booking_service INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_booking INT NOT NULL,
    id_service INT NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bs_booking FOREIGN KEY (id_booking) REFERENCES bookings(id_booking) ON DELETE CASCADE,
    CONSTRAINT fk_bs_service FOREIGN KEY (id_service) REFERENCES services(id_service)
);

CREATE TABLE payments (
    id_payment INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_booking INT NOT NULL,
    amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    method VARCHAR(80) NOT NULL DEFAULT 'Tien mat',
    paid_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payer_name VARCHAR(160),
    cashier_name VARCHAR(160),
    id_admin INT,
    note TEXT,
    CONSTRAINT fk_payments_booking FOREIGN KEY (id_booking) REFERENCES bookings(id_booking) ON DELETE CASCADE
);

CREATE TABLE reviews (
    id_review INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_booking INT NOT NULL UNIQUE,
    id_room INT NOT NULL,
    id_guest INT NOT NULL,
    room_rating DECIMAL(3,1) NOT NULL,
    service_rating DECIMAL(3,1) NOT NULL,
    comment TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'visible',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_reviews_booking FOREIGN KEY (id_booking) REFERENCES bookings(id_booking) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_room FOREIGN KEY (id_room) REFERENCES rooms(id_room) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_guest FOREIGN KEY (id_guest) REFERENCES guests(id_guest) ON DELETE CASCADE
);

CREATE TABLE security_logs (
    id_log INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type VARCHAR(20) NOT NULL DEFAULT 'guest',
    actor_id INT,
    action VARCHAR(120) NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'info',
    message TEXT,
    ip_address VARCHAR(45),
    user_agent VARCHAR(500),
    context_json TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_rooms_hotel_active_status ON rooms(id_hotel, is_active, status);
CREATE INDEX idx_bookings_room_status_dates ON bookings(id_room, status, check_in, check_out);
CREATE INDEX idx_bookings_guest_status ON bookings(id_guest, status);
CREATE INDEX idx_payments_booking_paid ON payments(id_booking, paid_at);
CREATE INDEX idx_security_action_created ON security_logs(action, created_at);
