CREATE TABLE payment_gateway_transactions (
    id_gateway_tx INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_booking INT NOT NULL,
    id_payment INT,
    provider VARCHAR(40) NOT NULL,
    app_trans_id VARCHAR(80) NOT NULL,
    amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    order_url TEXT,
    gateway_trans_id VARCHAR(80),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP,
    CONSTRAINT uq_provider_app_trans UNIQUE (provider, app_trans_id),
    CONSTRAINT fk_pgt_booking FOREIGN KEY (id_booking) REFERENCES bookings(id_booking) ON DELETE CASCADE,
    CONSTRAINT fk_pgt_payment FOREIGN KEY (id_payment) REFERENCES payments(id_payment) ON DELETE SET NULL
);

CREATE INDEX idx_pgt_booking ON payment_gateway_transactions(id_booking);
CREATE INDEX idx_pgt_status_created ON payment_gateway_transactions(status, created_at);
